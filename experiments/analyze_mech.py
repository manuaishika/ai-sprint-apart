"""Figure 4 and tables for the follow-up experiments.  python -m experiments.analyze_mech"""
import os

import numpy as np
import pandas as pd

from .analyze import ci
from .style import BLUE, INK2, MUTED, ORANGE, plt

R = os.path.join(os.path.dirname(__file__), "..", "results")
FIG = os.path.join(R, "figures")


def main():
    rel = pd.read_csv(f"{R}/mech_relative.csv")
    iv = pd.read_csv(f"{R}/interventions.csv")
    dl = pd.read_csv(f"{R}/mech_delay.csv")
    cv = pd.read_csv(f"{R}/mech_convergence.csv")
    out = ["# Follow-up experiments (auto-generated by experiments/analyze_mech.py)\n"]

    fig, axes = plt.subplots(2, 2, figsize=(9.5, 5.8))

    # A: which one-bit signals work
    ax = axes[0, 0]
    base = iv[iv.label == "baseline"].delta
    sig = [("exact price", "3.9 bits", base),
           ("relative: lower / equal / higher", "1.6 bits", rel[rel.signal.str.startswith("relative 3")].delta),
           ("absolute: upper / lower half", "1 bit", rel[rel.signal.str.startswith("absolute 2")].delta),
           ("relative: rival ≥ mine?", "1 bit", rel[rel.signal.str.startswith("relative 2")].delta),
           ("nothing", "0 bits", rel[rel.signal.str.startswith("absolute 1")].delta)]
    rows = []
    for i, (name, bits, x) in enumerate(sig):
        m, lo, hi = ci(x)
        rows.append({"signal": name, "bits": bits, "delta": f"{m:.2f} ({lo:.2f}–{hi:.2f})"})
        ax.barh(i, m, color=ORANGE if "≥" in name else BLUE, height=0.62)
        ax.plot([lo, hi], [i, i], color=INK2, lw=0.9)
        ax.text(max(hi, m) + 0.03, i, f"{m:.2f}", va="center", fontsize=7.5, color=INK2)
    ax.set_yticks(range(len(sig)), [f"{s[0]}  ({s[1]})" for s in sig], fontsize=7.5)
    ax.invert_yaxis()
    ax.set_xlim(-0.05, 1.0)
    ax.set_xlabel("collusion index Δ")
    ax.grid(axis="y", visible=False)
    ax.set_title("A   Not every one-bit signal works")
    out += ["## Which signals sustain collusion?\n", pd.DataFrame(rows).to_markdown(index=False) + "\n"]

    # B: delay -> fewer agents learn to retaliate
    ax = axes[0, 1]
    s = dl.drop_duplicates(["delay", "seed"]).copy()
    s["learned"] = s.intended < -0.1
    ds = sorted(s.delay.unique())
    rows = []
    for grp, col, lab in [(True, BLUE, "learned to retaliate"), (False, MUTED, "did not")]:
        xs, ys, lo, hi = [], [], [], []
        for d in ds:
            g = s[(s.delay == d) & (s.learned == grp)].delta
            if len(g) >= 5:
                m, l, h = ci(g)
                xs.append(d), ys.append(m), lo.append(l), hi.append(h)
        ax.fill_between(xs, lo, hi, color=col, alpha=0.15, lw=0)
        ax.plot(xs, ys, marker="o", color=col, label=lab, mec="white", mew=0.8)
    for d in ds:
        share = s[s.delay == d].learned.mean()
        ax.text(d, 0.96, f"{share:.0%}", ha="center", fontsize=7.5, color=BLUE)
        rows.append({"delay": d, "share_learned": f"{share:.0%}", "delta_all": f"{s[s.delay == d].delta.mean():.2f}",
                     "intended": f"{s[s.delay == d].intended.mean():.2f}",
                     "corr(delta,intended)": f"{np.corrcoef(s[s.delay == d].delta, s[s.delay == d].intended)[0, 1]:.2f}"})
    ax.text(ds[-1] + 0.15, 0.96, "learned", fontsize=7, color=BLUE, va="center")
    ax.set_xticks(ds)
    ax.set_ylim(0, 1.05)
    ax.set_xlabel("observation delay (periods)")
    ax.set_ylabel("collusion index Δ")
    ax.legend(loc="lower left")
    ax.set_title("B   Delay: fewer agents learn to retaliate")
    out += ["## Delay mechanism: who learns to retaliate?\n", pd.DataFrame(rows).to_markdown(index=False) + "\n"]

    # C: enacted response aligned to the first period the rival could see the cut
    ax = axes[1, 0]
    cols = {0: BLUE, 1: ORANGE, 2: "#1baf7a", 4: MUTED}
    for d in ds:
        g = dl[dl.delay == d].groupby("lag").resp.mean()
        lags = np.array(g.index) - d            # 1 = first period the rival can see the cut
        keep = lags >= 1
        ax.plot(lags[keep], g.values[keep], marker="o", ms=3.5, color=cols[d], label=f"delay {d}")
    ax.axhline(0, color=INK2, lw=0.8)
    ax.set_xlabel("periods after the rival can first see the cut")
    ax.set_ylabel("rival's price response\n(units of p_M − p_N)")
    ax.legend(loc="lower right", ncol=2)
    ax.set_title("C   Enacted retaliation, aligned")

    # D: convergence
    ax = axes[1, 1]
    cc = {"jitter p=0.05": BLUE, "jitter p=0.1": ORANGE, "noise eps=0.2": "#1baf7a"}
    rows = []
    for name, col in cc.items():
        xs, ys, lo, hi = [], [], [], []
        for t in sorted(cv.T_max.unique()):
            g = cv[(cv.condition == name) & (cv.T_max == t)].delta
            m, l, h = ci(g)
            xs.append(t / 1e6), ys.append(m), lo.append(l), hi.append(h)
            rows.append({"condition": name, "T_max (M periods)": t / 1e6, "delta": f"{m:.2f} ({l:.2f}–{h:.2f})",
                         "converged": f"{cv[(cv.condition == name) & (cv.T_max == t)].converged.mean():.0%}"})
        ax.fill_between(xs, lo, hi, color=col, alpha=0.15, lw=0)
        ax.plot(xs, ys, marker="o", color=col, label=name, mec="white", mew=0.8)
    ax.set_xscale("log", base=2)
    ax.set_xticks([1, 3, 6, 12], ["1", "3", "6", "12"])
    ax.set_ylim(0, 0.8)
    ax.set_xlabel("training length (millions of periods)")
    ax.set_ylabel("collusion index Δ")
    ax.legend(loc="lower left")
    ax.set_title("D   Δ settles even when no session converges")
    out += ["## Does Δ settle when sessions never converge?\n", pd.DataFrame(rows).to_markdown(index=False) + "\n"]

    fig.tight_layout(w_pad=2.5, h_pad=2.2)
    fig.savefig(f"{FIG}/mechanisms.png")
    open(f"{R}/mech_summary.md", "w").write("\n".join(out))
    print("\n".join(out))


if __name__ == "__main__":
    main()
