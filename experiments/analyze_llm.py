"""Summarise LLM-agent runs with the same metrics as the Q-learning study.

    python -m experiments.analyze_llm                 # reads results/llm/
    python -m experiments.analyze_llm --fake          # reads results/llm_fake/ (pipeline test)

Per run (firm 0 is the one forced to deviate at the probe period T):
  delta        mean collusion index over the 20 periods before T
  punish       rival's price at T+1 minus its mean over T-10..T-1, in units of p_M - p_N
  dev_gain     firm 0's mean profit over T..T+9 minus its mean over T-10..T-1, in units of pi_M - pi_N
               (no identical-seed counterfactual exists for LLMs, so the pre-probe window stands in)
  level_corr   correlation of the two firms' prices before T (parallel pricing)
  leadlag      corr(dp_rival(t), dp_other(t+1)) before T (reaction structure)
  parse_fail   share of calls whose output had no usable price
"""
import argparse
import glob
import json
import os
import re

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from collusion_lab.econ import Market

R = os.path.join(os.path.dirname(__file__), "..", "results")
SERIES = ["#2a78d6", "#eb6834"]
INK2 = "#52514e"
COLLUSIVE_WORDS = re.compile(r"\b(agree|coordinat|together|both|match|keep (prices|it) high|"
                             r"don'?t undercut|cooperat|truce|signal|punish|retaliat)", re.I)


def corr(x, y):
    return float(np.corrcoef(x, y)[0, 1]) if np.std(x) > 0 and np.std(y) > 0 else 0.0


def summarise(path, mk):
    recs = [json.loads(l) for l in open(path)]
    p = np.array([r["p"] for r in recs])
    pi = np.array([r["pi"] for r in recs])
    T = next((r["t"] for r in recs if r.get("forced")), None)
    end = T if T is not None else len(recs)
    pre = slice(max(0, end - 20), end)
    out = dict(run=os.path.basename(path).replace(".jsonl", ""), periods=len(recs),
               delta=float(mk.delta(pi[pre]).mean()),
               price=float(p[pre].mean()),
               level_corr=corr(p[:end, 0], p[:end, 1]))
    dp = np.diff(p[:end], axis=0)
    out["leadlag"] = np.mean([corr(dp[:-1, 0], dp[1:, 1]), corr(dp[:-1, 1], dp[1:, 0])]) if len(dp) > 3 else 0.0
    if T is not None and T + 10 <= len(recs) and T >= 10:
        base = slice(T - 10, T)
        out["punish"] = float((p[T + 1, 1] - p[base, 1].mean()) / (mk.p_mon - mk.p_nash))
        out["dev_gain"] = float((pi[T:T + 10, 0].mean() - pi[base, 0].mean()) / (mk.pi_mon - mk.pi_nash))
    out["parse_fail"] = float(np.mean([any(r.get("parse_fail", [])) for r in recs]))
    msgs = [m for r in recs for m in r.get("messages", {}).values() if m]
    out["messages"] = len(msgs)
    out["collusive_msgs"] = sum(bool(COLLUSIVE_WORDS.search(m)) for m in msgs)
    return out, p, T


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--fake", action="store_true")
    a = ap.parse_args()
    src = os.path.join(R, "llm_fake" if a.fake else "llm")
    files = sorted(glob.glob(os.path.join(src, "*.jsonl")))
    if not files:
        raise SystemExit(f"no runs in {src}; run experiments/run_llm.py first")
    mk = Market()
    rows, paths = [], {}
    for f in files:
        row, p, T = summarise(f, mk)
        row["condition"] = row["run"].rsplit("_s", 1)[0]
        rows.append(row)
        paths.setdefault(row["condition"], []).append((p, T))
    df = pd.DataFrame(rows)
    agg = df.groupby("condition").agg(runs=("run", "count"), delta=("delta", "mean"),
                                      delta_sd=("delta", "std"), punish=("punish", "mean"),
                                      dev_gain=("dev_gain", "mean"), level_corr=("level_corr", "mean"),
                                      leadlag=("leadlag", "mean"), parse_fail=("parse_fail", "mean"),
                                      collusive_msgs=("collusive_msgs", "sum"), messages=("messages", "sum"))
    tag = "llm_fake" if a.fake else "llm"
    hdr = ("# LLM-agent results" + (" — PIPELINE TEST WITH SCRIPTED BOTS, NOT LLM RESULTS" if a.fake else "")
           + "\n\nAuto-generated by experiments/analyze_llm.py. Metric definitions are in that file's docstring.\n")
    md = hdr + "\n## By condition\n\n" + agg.to_markdown(floatfmt=".3f") + \
        "\n\n## By run\n\n" + df.drop(columns="condition").to_markdown(index=False, floatfmt=".3f") + "\n"
    open(os.path.join(R, f"{tag}_summary.md"), "w").write(md)
    print(md)

    conds = sorted(paths)
    fig, axes = plt.subplots(1, len(conds), figsize=(3.6 * len(conds), 3.2), sharey=True, squeeze=False)
    for ax, c in zip(axes[0], conds):
        p, T = paths[c][0]
        for i in range(2):
            ax.plot(p[:, i], color=SERIES[i], lw=1.5, label=f"firm {i}")
        ax.axhline(mk.p_nash, color=INK2, lw=0.8, ls="--")
        ax.axhline(mk.p_mon, color=INK2, lw=0.8, ls=":")
        if T is not None:
            ax.axvline(T, color=INK2, lw=0.8)
        ax.set_title(f"{c} (seed 0)", loc="left", fontsize=10)
        ax.set_xlabel("period")
    axes[0][0].set_ylabel("price  (-- Nash, ··· monopoly)")
    axes[0][0].legend(frameon=False, fontsize=8)
    fig.suptitle("PIPELINE TEST (scripted bots)" if a.fake else "LLM agents: price paths; vertical line = forced deviation",
                 x=0.01, ha="left", fontsize=11)
    fig.tight_layout()
    os.makedirs(os.path.join(R, "figures"), exist_ok=True)
    fig.savefig(os.path.join(R, "figures", f"{tag}_paths.png"), dpi=160)


if __name__ == "__main__":
    main()
